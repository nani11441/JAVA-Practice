package Literals;

public class PrimitiveDataTypes {
    public static void main(String[] args) {
        // Integer literal
        int myInt = 100;
        System.out.println("Integer literal: " + myInt);

        // Floating-point literal
        double myDouble = 10.5;
        System.out.println("Floating-point literal: " + myDouble);

        // Character literal
        char myChar = 'A';
        System.out.println("Character literal: " + myChar);

        // String literal
        String myString = "Hello, World!";
        System.out.println("String literal: " + myString);

        // Boolean literal
        boolean myBoolean = true;
        System.out.println("Boolean literal: " + myBoolean);
    }
    
}
