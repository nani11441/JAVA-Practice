package VariableCreation;

public class Singlelinevariables {
    public static void main(String[] args) {
        // Declaring and initializing multiple variables of the same type in a single line
        int x = 5, y = 10, z = 15; // Declaring and initializing three integer variables

        // Displaying the values of the variables
        System.out.println("Value of x: " + x);
        System.out.println("Value of y: " + y);
        System.out.println("Value of z: " + z);
    }
    
}
