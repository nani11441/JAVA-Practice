package GlobalVariables;

public class localVaribles {
    public static void main(String[] args) {
        // Local variables (method-level variables)
        int a = 50; // Local variable
        String b = "Local Variable Example"; // Local variable

        // Displaying the values of the local variables
        System.out.println("Local Integer: " + a);
        System.out.println("Local String: " + b);
    }
    
}
