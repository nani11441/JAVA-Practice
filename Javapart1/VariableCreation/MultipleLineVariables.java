package VariableCreation;

public class MultipleLineVariables {
    public static void main(String[] args) {
        // Declaring multiple variables of the same type in a single line
        int a;
        a = 10; // Assigning value to variable a
        int b;
        b = 20; // Assigning value to variable b
        float c;
        c = 30.5f; // Assigning value to variable c     

        // Displaying the values of the variables
        System.out.println("Value of a: " + a);
        System.out.println("Value of b: " + b);
        System.out.println("Value of c: " + c);
    }
    
}
