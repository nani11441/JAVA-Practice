package Literals;

public class NonPrimitiveDatatype {
    public static void main(String[] args) {
        // Non-primitive data type: String
        String myString = "Hello, World!";
        System.out.println("Non-primitive data type (String): " + myString);

        // Non-primitive data type: Array
        int[] myArray = {1, 2, 3, 4, 5};
        System.out.print("Non-primitive data type (Array): ");
        for (int num : myArray) {
            System.out.print(num + " ");
        }
        System.out.println();

     
    }
    
}
