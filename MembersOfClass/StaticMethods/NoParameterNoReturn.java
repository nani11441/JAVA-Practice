package MembersOfClass.StaticMethods;

public class NoParameterNoReturn {
    //Static Method Without Arguments and Without Return Value//
    /*A static method that does not accept any parameters and does not return any value. */

    static void display() {
        System.out.println("Welcome to Java");
        System.out.println("Static Method");
    }

    public static void main(String[] args) {
         NoParameterNoReturn.display();
    }
}
    

