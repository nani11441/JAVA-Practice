class Concatination 
{
	public static void main(String[] args) 
	{

        int age=23;
		System.out.println(age);
		System.out.println("Age=" +age);
		System.out.println("Age="+ age +"year");


		System.out.println("Hello World!" +20);
		System.out.println("10"+10);
		System.out.println(91+"Hi");
	}
}
